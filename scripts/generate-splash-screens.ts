import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { decodePng, encodeIndexedPng } from './png.ts';

/**
 * RB-20: iOS launch images (`<link rel="apple-touch-startup-image">`), light and dark, portrait, iPhone only (owner
 * decision O9). iOS builds no splash screen from the manifest; without an image that matches the device it shows a
 * blank screen. Run by hand when the mark changes or Apple ships a new iPhone size, then commit the outputs; never
 * part of `npm run gates`, `npm run build` or CI:
 *
 *   node scripts/generate-splash-screens.ts
 *
 * Ruby's mark (`static/favicon.svg`) sits centred on `--bg`: `#fbfbfb` light, `#030303` dark (src/app.css). Chromium
 * draws each image with crisp edges (a handful of colours), then `scripts/png.ts` writes it as an opaque indexed PNG
 * of a few KB with no metadata. The script also writes the table the root layout and the tests read,
 * `src/lib/shared/splash-screens.ts`.
 *
 * Sizes: CSS points and scale of each iPhone portrait screen. Source: Apple Human Interface Guidelines, "Layout" ›
 * device screen sizes, cross-checked against https://iosref.com/res on 2026-10-26. Re-check both whenever a row is
 * added.
 */

export interface SplashDevice {
	/** CSS pixels, portrait. */
	width: number;
	height: number;
	scale: 2 | 3;
	/** Devices that share the size, for whoever adds the next row. */
	devices: string;
}

export const SPLASH_DEVICES: readonly SplashDevice[] = [
	{ width: 402, height: 874, scale: 3, devices: 'iPhone 16 Pro, 17, 17 Pro, 18 Pro' },
	{ width: 440, height: 956, scale: 3, devices: 'iPhone 16 Pro Max, 17 Pro Max' },
	{ width: 420, height: 912, scale: 3, devices: 'iPhone Air' },
	{ width: 393, height: 852, scale: 3, devices: 'iPhone 14 Pro, 15, 15 Pro, 16' },
	{ width: 430, height: 932, scale: 3, devices: 'iPhone 14 Pro Max, 15 Plus, 15 Pro Max, 16 Plus' },
	{ width: 390, height: 844, scale: 3, devices: 'iPhone 12, 13, 14, 16e' },
	{ width: 428, height: 926, scale: 3, devices: 'iPhone 12 Pro Max, 13 Pro Max, 14 Plus' },
	{ width: 375, height: 812, scale: 3, devices: 'iPhone X, XS, 11 Pro, 12 mini, 13 mini' },
	{ width: 414, height: 896, scale: 3, devices: 'iPhone XS Max, 11 Pro Max' },
	{ width: 414, height: 896, scale: 2, devices: 'iPhone XR, 11' },
	{ width: 375, height: 667, scale: 2, devices: 'iPhone SE (2nd, 3rd gen), 8' }
];

const SCHEMES = ['light', 'dark'] as const;
export type Scheme = (typeof SCHEMES)[number];

/** `--bg` per scheme, as in src/app.css. */
const SPLASH_BG: Record<Scheme, string> = { light: '#fbfbfb', dark: '#030303' };

/** Everything in static/splash/ together stays within this (a unit test checks it). */
export const SPLASH_BUDGET_BYTES = 1_000_000;

export const splashFile = (d: SplashDevice, scheme: Scheme) =>
	`splash/splash-${d.width * d.scale}x${d.height * d.scale}-${scheme}.png`;

/** The generated table: points, scale and one file per scheme, in the order the head lists them. */
function splashTable(): string {
	const rows = SPLASH_DEVICES.map(
		(d) =>
			`\t{ width: ${d.width}, height: ${d.height}, scale: ${d.scale}, light: '/${splashFile(d, 'light')}', dark: '/${splashFile(d, 'dark')}' }`
	);
	return (
		`// Generated by scripts/generate-splash-screens.ts (node scripts/generate-splash-screens.ts). Do not edit.\n` +
		`// iOS launch images (RB-20): portrait CSS points, device scale and the file per colour scheme.\n\n` +
		`export interface SplashScreen {\n\twidth: number;\n\theight: number;\n\tscale: 2 | 3;\n\tlight: string;\n\tdark: string;\n}\n\n` +
		`export const SPLASH_SCREENS: readonly SplashScreen[] = [\n${rows.join(',\n')}\n];\n`
	);
}

async function main(root: string) {
	const { chromium } = await import('@playwright/test');
	const mark = readFileSync(join(root, 'static/favicon.svg'), 'utf8');
	const dir = join(root, 'static', 'splash');
	rmSync(dir, { recursive: true, force: true });
	mkdirSync(dir, { recursive: true });
	const browser = await chromium.launch();
	let total = 0;
	try {
		const page = await browser.newPage({ deviceScaleFactor: 1 });
		for (const device of SPLASH_DEVICES) {
			const [w, h] = [device.width * device.scale, device.height * device.scale];
			// The mark is 96 points wide (whole device pixels), centred.
			const size = 96 * device.scale;
			const [left, top] = [Math.floor((w - size) / 2), Math.floor((h - size) / 2)];
			const svg = mark.replace(
				'<svg ',
				`<svg width="${size}" height="${size}" shape-rendering="crispEdges" `
			);
			for (const scheme of SCHEMES) {
				await page.setViewportSize({ width: w, height: h });
				await page.setContent(
					`<!doctype html><html><body style="margin:0;background:${SPLASH_BG[scheme]}">` +
						`<div style="position:fixed;left:${left}px;top:${top}px;line-height:0">${svg}</div></body></html>`
				);
				const png = encodeIndexedPng(decodePng(await page.screenshot({ type: 'png' })));
				writeFileSync(join(root, 'static', splashFile(device, scheme)), png);
				total += png.length;
				console.log(`wrote static/${splashFile(device, scheme)} (${png.length} bytes)`);
			}
		}
	} finally {
		await browser.close();
	}
	// Formatted with the repo's Prettier config, so `npm run lint` passes on the generated file as committed.
	const tablePath = join(root, 'src/lib/shared/splash-screens.ts');
	writeFileSync(
		tablePath,
		await format(splashTable(), { ...(await resolveConfig(tablePath)), filepath: tablePath })
	);
	console.log(
		`wrote src/lib/shared/splash-screens.ts; static/splash: ${readdirSync(dir).length} files, ${total} bytes (budget ${SPLASH_BUDGET_BYTES})`
	);
	if (total > SPLASH_BUDGET_BYTES) throw new Error('static/splash exceeds its budget');
}

if (import.meta.main) await main(join(import.meta.dirname, '..'));
